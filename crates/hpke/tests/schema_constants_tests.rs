#[test]
fn registered_identity_order_remains_exact() {
    // Every enum is repr(u16); these public identifiers are not length conversions.
    assert_eq!(
        HPKE_REGISTERED_KEMS.map(|value| value as u16),
        [16, 17, 18, 19, 20, 21, 22, 32, 33, 34, 48, 64, 65, 66, 80, 81, 25722]
    );
    assert_eq!(
        HPKE_REGISTERED_KDFS.map(|value| value as u16),
        [1, 2, 3, 16, 17, 18, 19]
    );
    assert_eq!(
        HPKE_REGISTERED_AEADS.map(|value| value as u16),
        [1, 2, 3, 65535]
    );
}

