import { classifyProtoScalars } from "./proto_scalar_policy.mjs";

/** Audit unmodified generator output against the schema's ownership slots. */
export function checkGeneratedOwners(schema, source) {
  const headers = [...source.matchAll(/^pub struct ([A-Za-z_]\w*)\s*\{/gmu)];
  const owners = new Map(headers.map((header, index) => [header[1],
    source.slice(header.index, headers[index + 1]?.index ?? source.length).replace(/\s+/gu, "")]));
  for (const { message, field, kind, optional } of classifyProtoScalars(schema)) {
    const owner = owners.get(message);
    const type = message === "CryptoKeyPair" && field === "secret_key"
      ? "PrivateBytes" : kind === "bytes" ? "SecretBytes" : "SecretString";
    const slot = optional ? `::core::option::Option<crate::${type}>` : `crate::${type}`;
    if (owner === undefined || !owner.includes(`impl::buffa::sensitive::ZeroizeOnDropfor${message}{}`) ||
      !owner.includes(`impl::core::ops::Dropfor${message}{`) ||
      !owner.includes(`::buffa::sensitive::Zeroize::zeroize(&mutself.${field})`) ||
      !(owner.includes(`pub${field}:${slot},`) || owner.includes(`pub${field}:::buffa::sensitive::List<crate::${type}>,`))) {
      return `${message}.${field}`;
    }
  }
  return null;
}

/** Crypto-specific checks complement the unchanged pinned shared release core. */
export function assertNativeBuffaReadiness(context, policy) {
  const { assertContains, assertNotContains, assertWorkflowPolicy, assertGeneratedArtifactsFresh, readText, fail } = context;
  const workflow = ".github/workflows/protobuf-ci.yml";
  assertWorkflowPolicy({
    path: workflow,
    required: ["BUFFA_VERSION: 0.1.0", "BUF_VERSION: 1.75.0", ...policy.paths.map((path) => `- "${path}"`)],
    forbidden: ["cargo test -p", "cargo install protoc-gen-buffa", "redact_crypto_proto_debug.mjs"],
    usesSteps: [{ name: "Install buf", uses: "bufbuild/buf-action@37ac33d8960807670a6e9719080e885197b09cc6" }],
    runSteps: [
      { name: "Install pinned Buffa generators", run: 'cargo install reallyme-protoc-gen-buffa --version "=$BUFFA_VERSION" --locked\ncargo install reallyme-protoc-gen-buffa-packaging --version "=$BUFFA_VERSION" --locked' },
      { name: "Check release readiness generated freshness", run: "node scripts/run_pinned_release_readiness.mjs --generated-freshness" },
    ],
  });
  const config = "buf.gen.yaml";
  for (const needle of ["local: protoc-gen-reallyme-buffa\n", "local: protoc-gen-reallyme-buffa-packaging\n",
    "strategy: all", "zeroize_in=.reallyme.crypto.v1", "unknown_fields=false", "deny_unknown_json_fields=true",
    "json_policy_type=crate::SecretBytes", "json_policy_type=crate::PrivateBytes", "json_policy_type=crate::SecretString",
    "deny_view_json=.reallyme.crypto.v1.CryptoOperationRequest", "extern_path=.reallyme.crypto.v1.CryptoErrorReason=crate::enum_contracts::CryptoErrorReason"]) {
    assertContains(config, needle);
  }
  assertNotContains(config, "allow_unmatched_message_rules");
  assertContains("Cargo.toml", 'buffa = { package = "reallyme-buffa", version = "=0.1.0", default-features = false }');
  assertContains("crates/proto/Cargo.toml", '"buffa/zeroize"');
  for (const path of ["wire/codec.rs", "wire/error.rs", "operation_response_wire.rs", "guarded_view.rs"]) {
    assertContains(`crates/proto/src/${path}`, ".reject_unknown_fields()");
  }
  const generated = "crates/proto/src/generated/buffa/reallyme.crypto.v1.crypto.rs";
  const generatedSource = readText(generated);
  if (!generatedSource.startsWith("// @generated by reallyme-buffa-codegen 0.1.0. DO NOT EDIT.\n")) {
    fail(`${generated} does not identify the pinned Buffa generator`);
  }
  assertNotContains(generated, "__buffa_unknown_fields");
  assertNotContains(generated, "crate::merge_sensitive");
  const failingField = checkGeneratedOwners(readText(policy.protoPath), generatedSource);
  if (failingField !== null) fail(`generated protobuf field lacks a clearing owner: ${failingField}`);
  assertContains("crates/proto/src/generated/enum_contracts.rs", "pub use crate::error_types::CryptoErrorReason;");
  assertContains("crates/proto/src/generated/error_contract.rs", "pub struct CryptoError {\n    reason: CryptoErrorReason,");
  assertNotContains("crates/proto/src/generated/error_contract.rs", "impl Default for CryptoError {");
  for (const name of ["CryptoOperationRequest", "CryptoOperationResponse", "CryptoOperationResult"]) {
    assertContains("crates/proto/src/generated/public.rs", `pub type ${name}OwnedView =`);
    assertNotContains("crates/proto/src/generated/buffa/reallyme.crypto.v1.crypto.__view.rs",
      `impl ::buffa::HasMessageView for super::super::${name} {`);
    assertContains("gen/swift/reallyme/crypto/v1/crypto.pb.swift", `ReallyMeProto${name}(<redacted>)`);
    assertContains(`gen/java/me/really/crypto/v1/${name}.java`, `${name}{<redacted>}`);
  }
  if (policy.generatedFreshnessMode) assertGeneratedArtifactsFresh({
    generatedPaths: ["crates/hpke/src/generated", "crates/proto/src/generated", "crates/proto/tests/fixtures/guarded/generated", "packages/ts/src/proto/generated", "gen"],
    commands: [["buf", ["lint"]], ["node", ["scripts/generate_protobuf.mjs"]],
      ["cargo", ["run", "-p", "crypto-conformance-vectors", "--bin", "gen_vectors"]]],
  });
}
